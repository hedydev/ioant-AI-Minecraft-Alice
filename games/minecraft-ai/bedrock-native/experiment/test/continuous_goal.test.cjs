'use strict'
const test=require('node:test'),assert=require('node:assert/strict')
const fs=require('node:fs'),os=require('node:os'),path=require('node:path')
const {ContinuousGoal}=require('../src/continuous_goal.cjs')
const fixture=()=>{
 let now=100000
 const events=[]
 const g=new ContinuousGoal({clock:()=>now,
   log:{log:(...args)=>events.push(args)}})
 return {g,events,get now(){return now},advance:n=>now+=n}
}
test('resource objective survives GATHER and EXPLORE task IDLE boundaries, blocked remains real',()=>{
 const {g}=fixture()
 assert.equal(g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false}),true)
 const identity=g.snapshot().revision
 assert.equal(g.snapshot().step,'ACQUIRE_WOOD')
 g.begin('GATHER','自主任务')
 assert.equal(g.snapshot().phase,'ACTING')
 g.failed('GATHER','自主任务')
 assert.equal(g.snapshot().phase,'BLOCKED')
 assert.equal(g.snapshot().reason,'tool_exception')
 g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false})
 assert.equal(g.snapshot().phase,'BLOCKED','IDLE must not make failure disappear')
 assert.equal(g.snapshot().revision,identity)
 g.begin('EXPLORE','自主探索')
 g.finish('EXPLORE','自主探索',{ok:false,reason:'scout_server_endpoint_unconfirmed',
   localEstimateBlocks:1.41,serverMovementVerified:false})
 assert.equal(g.snapshot().goal,'LEARN_WEAPON')
 assert.equal(g.snapshot().step,'DISCOVER_RESOURCES')
 assert.equal(g.snapshot().phase,'BLOCKED')
 assert.equal(g.snapshot().reason,'server_position_unconfirmed')
 g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false})
 assert.equal(g.snapshot().phase,'BLOCKED')
 assert.equal(g.snapshot().step,'DISCOVER_RESOURCES')
})
test('inventory-verified materials advance same long-term goal; equipment finishes it',()=>{
 const {g}=fixture()
 g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false})
 g.begin('GATHER','自主任务')
 g.finish('GATHER','自主任务',{ok:true,verifiedDelta:1})
 assert.equal(g.snapshot().phase,'READY')
 assert.equal(g.snapshot().step,'ACQUIRE_WOOD')
 g.reconcile({plan:'LEARN_WEAPON',wood:1,hasWeapon:false})
 assert.equal(g.snapshot().step,'ACQUIRE_WOOD')
 g.reconcile({plan:'LEARN_WEAPON',wood:2,hasWeapon:false})
 assert.equal(g.snapshot().step,'CRAFT_WEAPON')
 assert.equal(g.snapshot().reason,'inventory_transition_verified')
 g.begin('CRAFT','自主任务')
 g.finish('CRAFT','自主任务',{ok:true,verifiedDelta:1})
 assert.equal(g.snapshot().goal,'LEARN_WEAPON','a tool result is not verified equipment')
 g.reconcile({plan:'COLLECT_WOOD',wood:2,hasWeapon:true})
 assert.equal(g.snapshot().goal,'COLLECT_WOOD')
 assert.equal(g.lastCompleted.goal,'LEARN_WEAPON')
 assert.equal(g.lastCompleted.reason,'inventory_transition_verified')
})
test('pause/resume and real WAIT are distinct from short-lived Core IDLE',()=>{
 const {g}=fixture()
 g.reconcile({plan:'COLLECT_WOOD',wood:0,hasWeapon:true})
 g.wait('waiting_for_daylight')
 assert.equal(g.snapshot().phase,'WAITING')
 g.interrupt('user_stop')
 assert.equal(g.snapshot().phase,'PAUSED')
 g.wait('review_scheduled')
 assert.equal(g.snapshot().phase,'PAUSED')
 assert.equal(g.snapshot({humanOverride:true}).phase,'PAUSED')
 g.resume()
 assert.equal(g.snapshot().phase,'READY')
 assert.equal(g.snapshot({mode:'companion'}).phase,'PAUSED')
})
