test('restarted objective is only an untrusted hint until fresh inventory reconciliation',()=>{
 const dir=fs.mkdtempSync(path.join(os.tmpdir(),'alice-goal-test-'))
 const file=path.join(dir,'long-term-goal.json')
 try{
   let now=100000
   const g=new ContinuousGoal({clock:()=>now,file,log:{log(){}}})
   g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false})
   assert.equal(JSON.parse(fs.readFileSync(file,'utf8')).goal,'LEARN_WEAPON')
   assert.equal(fs.statSync(file).mode&0o777,0o600)
   const second=new ContinuousGoal({clock:()=>now+1000,file,log:{log(){}}})
   assert.equal(second.snapshot().phase,'WAITING')
   assert.equal(second.snapshot().step,'REVALIDATE')
   assert.equal(second.snapshot().verifiedWood,0)
   second.reconcile({plan:'LEARN_WEAPON',wood:2,hasWeapon:false})
   assert.equal(second.snapshot().step,'CRAFT_WEAPON')
   assert.equal(second.snapshot().phase,'READY')
   fs.unlinkSync(file)
   fs.symlinkSync('elsewhere.json',file)
   const third=new ContinuousGoal({clock:()=>now+2000,file,log:{log(){}}})
   assert.equal(third.snapshot(),null,'do not follow symlink to stale goal')
   assert.equal(third.lastError,'load_unavailable')
 }finally{fs.rmSync(dir,{recursive:true,force:true})}
})

test('night shelter has priority without falsely completing interrupted weapon goal',()=>{
 const {g}=fixture()
 g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false})
 g.reconcile({plan:'SECURE_SHELTER',wood:0,hasWeapon:false})
 assert.equal(g.snapshot().goal,'SECURE_SHELTER')
 assert.equal(g.snapshot().step,'BUILD_SHELTER')
 assert.equal(g.snapshot().suspendedGoal,'LEARN_WEAPON')
 assert.equal(g.snapshot().lastCompleted,null)
 g.wait('shelter_position_unconfirmed')
 assert.equal(g.snapshot().phase,'WAITING')
 assert.equal(g.snapshot().reason,'shelter_position_unconfirmed')
 g.reconcile({plan:'LEARN_WEAPON',wood:0,hasWeapon:false})
 assert.equal(g.snapshot().goal,'LEARN_WEAPON')
 assert.equal(g.snapshot().reason,'priority_changed')
 assert.equal(g.snapshot().lastCompleted,null,
   'returning to normal daytime work does not mean shelter was built')
})
